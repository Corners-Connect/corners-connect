"""Count the videos in each stage and write them where the city can read them.

Run after adding or moving a video file:  py -3 video-production/status.py
Counts every .md file in a stage folder except TEMPLATE.md and anything with
"-example-" in its name, so the numbers are real videos only.
"""
from pathlib import Path

here = Path(__file__).resolve().parent
out = here.parent / "corners-city" / "board" / "video-status.js"
stages = ["ideas", "scripts", "recordings", "edits", "posts"]

counts = {
    s: sum(1 for f in (here / s).glob("*.md") if f.name != "TEMPLATE.md" and "-example-" not in f.name)
    for s in stages
}
out.write_text(
    "// Generated by video-production/status.py. Do not edit by hand.\n"
    "export const VIDEO_STATUS = " + str(counts).replace("'", "'") + ";\n",
    encoding="utf-8",
)
print(counts)
